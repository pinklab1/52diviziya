-- Неполная дата выбытия — как в документе (25.11.2026).
--
-- date_to — календарная дата: по ней считается и сортируется. У автора
-- часто известен только месяц: «__.08.1942», «__.__.1947», «между 25.10.1944
-- и 04.11.1944», «00.08.42 г.». В date_to такое не записать, поэтому импорт
-- клал это в примечание («дата выбытия: __.08.1942»), и на сайте этого не
-- было видно. Теперь — отдельное текстовое поле, сайт показывает его
-- «Выбыл: август 1942». Если известна полная дата, date_to_text пуст.

ALTER TABLE service_records ADD COLUMN IF NOT EXISTS date_to_text text;

COMMENT ON COLUMN service_records.date_to_text IS
  'Дата выбытия, как в документе, если она неполная (__.08.1942). Полная — в date_to.';

-- Судьба словами автора — дословно из колонки «Судьба» таблицы: «погиб»,
-- «погибла», «умер от отравления», «погиб (автокатастрофа)». outcome —
-- общая категория для фильтров и подсчётов, а на карточке в скобках после
-- даты смерти показывается это поле.
ALTER TABLE persons ADD COLUMN IF NOT EXISTS fate_text text;

COMMENT ON COLUMN persons.fate_text IS
  'Судьба дословно из таблицы автора («погибла», «умер от отравления»). Категория — в outcome.';

-- Перенос из примечаний: «…; дата выбытия: X; …» → date_to_text = X.
UPDATE service_records
   SET date_to_text = trim(substring(note FROM 'дата выбытия:\s*([^;]*)')),
       note = NULLIF(trim(BOTH '; ' FROM regexp_replace(note, '\s*;?\s*дата выбытия:\s*[^;]*', '', 'g')), '')
 WHERE note ~ 'дата выбытия:' AND date_to_text IS NULL;
