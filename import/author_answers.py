def _norm(s):
    return ' '.join((s or '').lower().replace('ё', 'е').split())


def split_comment(comment):
    """«Оставить:: Батищев …» → ('оставить', 'Батищев …');
    «тот же человек (г.р. 1921)» → ('тот же человек', 'г.р. 1921')."""
    text = ' '.join(str(comment or '').split())
    m = re.match(r'([^:(]*)(?:[:(]+\s*(.*?)\)?)?\s*$', text)
    head = _norm(m.group(1)).strip(' ,«»')
    rest = (m.group(2) or '').strip(' :,')
    # хвост «… 29.12.43   Оставить:» — автор дописал слово ещё раз
    rest = re.sub(r'\s*Оставить:?\s*$', '', rest, flags=re.I).strip(' ,')
    return head, rest


def parse_person(text, ranks):
    """«Абросимов Михаил Федорович, 1910, младший лейтенант, командир
    стрелковой роты, 439 сп, погиб, 01.10.42» → поля строки списка."""
    m = re.match(r'([^,]+?)\s*,\s*(\d{4}|19\?\?)\s*(?:г\.)?\s*,?\s*(.*)$', text)
    if not m:
        return None
    name, year, tail = m.group(1), m.group(2), m.group(3).strip(' ,')
    out = {'name': name.split(), 'year': year if year.isdigit() else None,
           'rank': None, 'role': None, 'unit': None, 'fate': None,
           'out_date': None, 'out_reason': None}

    fm = re.search(r'(' + '|'.join(FATES) + r')\s*(\([^)]*\))?\s*,?\s*([\d.]+)?\s*$', tail)
    if fm:
        word, note = fm.group(1), fm.group(2)
        out['fate'] = 'пропал без вести (попал в плен)' if word == 'попал в плен' else word
        if note:
            out['fate'] += ' ' + note
        out['out_reason'] = word + (' ' + note if note else '')
        out['out_date'] = fm.group(3).strip('.') if fm.group(3) else None
        tail = tail[:fm.start()].strip(' ,')

    um = re.search(r'(\d+)\s*(сп|ап|оиптд|орр|санб|двл|сд)$', tail)
    if um:
        out['unit'] = f'{um.group(1)} {um.group(2)}'
        tail = tail[:um.start()].strip(' ,')

    for rank in sorted(set(ranks) | set(EXTRA_RANKS), key=len, reverse=True):
        if _norm(tail).startswith(_norm(rank)) and tail[len(rank):len(rank) + 1] in ('', ' ', ','):
            out['rank'] = tail[:len(rank)]
            tail = tail[len(rank):].strip(' ,')
            break
    out['role'] = tail or None
    return out


def interpret(kind, comment, ranks):
    """Комментарий автора → (решение, поправка) или None, если ответа нет.
    kind — тип строки сверки (KINDS в import_komsostav.py)."""
    head, rest = split_comment(comment)
    if not head and not rest:
        return None
    fix = {}

    if kind in ('same', 'match'):
        if head in ('обновить', 'последняя версия', 'остается', 'надо', 'включить', 'добавить'):
            return 'Обновить', fix
        if head in ('не обновлять', 'прежняя версия'):
            return 'Не обновлять', fix

    elif kind == 'new':
        if head == 'добавить':
            return 'Добавить', fix

    elif kind == 'only_db':
        data = parse_person(rest, ranks) if rest else None
        if head in ('оставить', 'надо', 'добавить') and data:
            return 'Обновить', {'data': data}
        if rest:
            raise ValueError(f'не разобраны данные человека: «{comment}»')
        if head == 'оставить':
            return 'Оставить', fix
        if head == 'удалить':
            return 'Удалить', fix

    elif kind == 'disputed':
        if head in ('разные люди', 'новый человек'):
            return 'Новый человек', fix
        if head == 'удалить':
            return 'Не добавлять', fix
        if head in ('прежняя версия', 'оставить вторую'):
            # «прежняя» — как на сайте: и написание, и год
            return 'Тот же человек', {'base_name': True, 'base_year': head == 'прежняя версия'}
        if head in ('тот же человек', 'один человек', 'последняя версия',
                    'надо', 'обновить', 'добавить', 'оставить'):
            ym = re.search(r'г\.\s*р\.\s*(\d{4})', rest)
            if ym:
                fix['year'] = ym.group(1)
            elif rest:
                # «надо: Бухинник», «(Владкевич)», «Гулеватый Кузьма Андреевич, 1913, …»
                fix['spelling'] = rest.split(',')[0].strip()
            if head in ('надо', 'обновить', 'добавить', 'оставить') and not rest:
                return None
            return 'Тот же человек', fix

    elif kind == 'twin':
        if head in ('объединить', 'объдинить'):
            return 'Объединить', fix
        if head == 'удалить':
            return 'Удалить', fix
        if head == 'разные люди':
            return 'Разные люди', fix

    elif kind == 'list_twin':
        if head in ('оставить первую', 'оставить вторую', 'разные люди'):
            return head.capitalize(), fix
        if head == 'удалить':
            # «удалить» в строке первой из пары — удалить её, оставить вторую
            return 'Оставить вторую', fix

    raise ValueError(f'непонятный комментарий: «{comment}»')
