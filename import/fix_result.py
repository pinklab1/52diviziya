def fix_role(role_str: str | None, birth_year: int | None) -> tuple:
    if not role_str:
        return role_str, birth_year

    s = role_str.strip()
    m = ROLE_YEAR_RE.match(s)
    if not m:
        return role_str, birth_year

    year = int(m.group(1))
    rest = m.group(2).strip().lower()

    # Обновляем год рождения если не задан
    new_birth_year = birth_year if birth_year is not None else year

    # Ищем расшифровку — по убыванию длины ключа
    for abbr in sorted(ROLES_FIX.keys(), key=len, reverse=True):
        if rest == abbr or rest.startswith(abbr):
            return ROLES_FIX[abbr], new_birth_year

    # Не нашли — возвращаем хотя бы без года
    return rest, new_birth_year


def process(data: list) -> tuple[list, int]:
    fixed = 0
    for person in data:
        by = person.get('birth_year')
        for role_rec in person.get('roles', []):
            new_role, new_by = fix_role(role_rec.get('role'), by)
            if new_role != role_rec.get('role'):
                role_rec['role'] = new_role
                fixed += 1
            if new_by != by:
                person['birth_year'] = new_by
                by = new_by
    return data, fixed


def main():
    if len(sys.argv) < 2:
        print("Использование: python fix_result.py input.json [output.json]")
        sys.exit(1)

    input_file = sys.argv[1]
    output_file = sys.argv[2] if len(sys.argv) > 2 else input_file.replace('.json', '_fixed.json')

    with open(input_file, encoding='utf-8') as f:
        data = json.load(f)

    data, fixed = process(data)

    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Исправлено полей: {fixed}")
    print(f"Сохранено: {output_file}")


if __name__ == '__main__':
    main()
