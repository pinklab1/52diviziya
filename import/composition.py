"""
composition.py — состав, к которому относится человек: командный,
политический, сержантский или рядовой (решение автора, 24.11.2026).

Составы не пересекаются. Определяется по званию и должности во всех
записях о службе:
- политический — политическое звание (политрук, комиссар, замполитрука) или
  политическая должность при любом звании: после осени 1942 года
  политработники носят обычные звания, и «майор, замполит батальона» или
  «старшина, комсорг батальона» видны только по должности. Обслуга
  политотдела (машинистка, автоматчик, ординарец замполита) — по званию;
- командный — офицерские звания (включая военврачей, техников, интендантов)
  или, если звание не указано, офицерская должность;
- сержантский — сержанты и старшины;
- рядовой — красноармейцы, ефрейторы.
Порядок важен: политический перекрывает командный.

Те же правила — в frontend/index.html (функция composition): цифры таблицы
и фильтров сайта должны совпадать.
"""

import re

COMPOSITIONS = ['Командный', 'Политический', 'Сержантский', 'Рядовой']

POLIT_RANK = r'политрук|комиссар|замполитрука'
POLIT_ROLE = (r'замполит|по политической|политрук|военком|комиссар|парторг|'
              r'партийный организатор|комсорг|комсомольский организатор|агитатор|'
              r'пропагандист|политотдел|политического отдела|политработник')
# Служит при политотделе или замполите, но сам не политработник.
POLIT_STAFF = (r'^(секретарь-машинистка|машинистка|автоматчик|ординарец|шофер|шофёр|водитель|'
               r'писарь|повар|связной|посыльный|переводчик|фотограф)')
OFFICER_RANK = (r'генерал|полковник|майор|капитан|лейтенант|военврач|военфельдшер|'
                r'ветфельдшер|военинженер|воентехник|интендант|техник')
OFFICER_ROLE = r'^(командир (взвода|роты|батальона|дивизиона|батареи|полка)|начальник|офицер|адъютант|помощник начальника штаба)'
SERGEANT_RANK = r'сержант|старшина'
PRIVATE_RANK = r'красноармеец|ефрейтор|рядов'


def of_record(rank, role):
    rank, role = (rank or '').lower(), (role or '').lower().strip()
    officer = re.search(OFFICER_RANK, rank) or (not rank and re.search(OFFICER_ROLE, role))
    if re.search(POLIT_RANK, rank) or (re.search(POLIT_ROLE, role) and not re.search(POLIT_STAFF, role)):
        return 'Политический'
    if officer:
        return 'Командный'
    if re.search(SERGEANT_RANK, rank):
        return 'Сержантский'
    if re.search(PRIVATE_RANK, rank):
        return 'Рядовой'
    return None


def of_person(records):
    found = {of_record(s.get('rank'), s.get('role')) for s in records}
    for c in ('Политический', 'Командный', 'Сержантский', 'Рядовой'):
        if c in found:
            return c
    return None
